"""
tools/mail_sender.py

Send RTL verification summary email.

`send_email_message` is the plain (non-tool) function used by the agent
tool and by the debug-fix stage. Email is opt-in: it only sends when
EMAIL_SENDER, EMAIL_PASSWORD and EMAIL_RECEIVER are all configured.
"""

import os
import smtplib

from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

try:
    from dotenv import load_dotenv
except Exception:
    def load_dotenv():
        return None

try:
    from langchain.tools import tool
except Exception:
    def tool(func):
        return func

from state import verification_state

load_dotenv()


def send_email_message(subject, body, host="smtp.gmail.com", port=587, timeout=30):
    """
    Send an email using the EMAIL_SENDER / EMAIL_PASSWORD / EMAIL_RECEIVER
    environment configuration.

    Returns:
        Human-readable status string ("Email sent successfully...",
        "Email configuration missing." or "Email send failed: ...").
    """
    sender = os.getenv("EMAIL_SENDER")
    password = os.getenv("EMAIL_PASSWORD")
    receiver = os.getenv("EMAIL_RECEIVER")

    if not sender or not password or not receiver:
        return "Email configuration missing."

    message = MIMEMultipart()
    message["From"] = sender
    message["To"] = receiver
    message["Subject"] = subject
    message.attach(MIMEText(body, "plain"))

    try:
        server = smtplib.SMTP(host, port, timeout=timeout)
        try:
            server.starttls()
            server.login(sender, password)
            server.sendmail(sender, receiver, message.as_string())
        finally:
            try:
                server.quit()
            except Exception:
                pass

        return f"Email sent successfully to {receiver}"

    except Exception as e:
        return f"Email send failed: {e}"


@tool
def send_email_report() -> str:
    """
    Send RTL verification summary email.
    """
    sender = os.getenv("EMAIL_SENDER")
    password = os.getenv("EMAIL_PASSWORD")
    receiver = os.getenv("EMAIL_RECEIVER")

    if not sender or not password or not receiver:
        return "Email configuration missing."

    rtl_analysis = verification_state.get("rtl_analysis", {})

    missing_edge_cases = verification_state.get(
        "missing_edge_cases",
        []
    )

    rtl_text = rtl_analysis.get(
        "analysis",
        "No RTL issues found."
    )

    edge_case_text = ""

    if missing_edge_cases:
        for case in missing_edge_cases:
            edge_case_text += f"- {case}\n"
    else:
        edge_case_text = "None"

    body = f"""
RTL Verification Summary

====================================

RTL Issues
------------------------------------

{rtl_text}

====================================

Missing Edge Cases
------------------------------------

{edge_case_text}

====================================

Generated by RTL Verification Agent
"""

    return send_email_message("RTL Verification Summary", body)
